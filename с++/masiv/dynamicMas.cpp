#include <iostream>

using namespace std;

// Динамический массив — это массив, размер которого можно выделять и изменять прямо во время работы программы
// Динамическая память может использоваться не только для массивов

int main() {
    
    int *nums = new int[3]; //мы внутырь указателя выделели память под 3 элемента
    nums[0] = 45;
    cout << nums[0] << endl;
    delete[] nums; // Очищаем память

    cout << "El:" << nums[0] << endl; // проверка


    return 0;
}