#include <iostream>
#include <string>

using namespace std;

// Шаблон функции (function template). 
// Ключевое слово template <typename T> говорит компилятору, что тип данных T 
// является универсальным. Функция сможет работать с массивами любых типов (int, float, char и т.д.).
template <typename T>
void print_arr(T* arr, int len) {
    for(int i = 0; i < len; i++)
        cout << *(arr + i) << " "; // Вывод элементов через указатели и арифметику

    cout << endl;
}


int main() {
    // 1. Работа с массивом целых чисел (int)
    int arr1[] = { 5, 6, 3, 2, 0, -4};
    
    // Явное указание типа шаблона <int> (хотя компилятор может понять его и автоматически)
    print_arr<int>(arr1, 6);

    // 2. Работа с массивом чисел с плавающей точкой (float)
    float arr2[] = {2.2, 3.2, 4.71};
    
    // Неявное использование шаблона: компилятор сам догадывается, 
    // что вместо T нужно подставить float на основе переданного массива arr2.
    print_arr(arr2, 3);

    return 0;
}