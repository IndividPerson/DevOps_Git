#include <iostream>
#include <string>

using namespace std;

// Шаблон класса (class template). 
// Буква T позволяет классу работать с массивами любых типов данных (int, float и т.д.).
template <class T>
class Arrays {
private:
    int len;    // Длина массива
    T* arr;     // Указатель на динамический массив универсального типа T
public:
    // Конструктор: принимает указатель на внешний массив и его размер
    Arrays(T* a, int len) {
        this->len = len;
        
        // Выделяем динамическую память в куче под новый массив типа T
        arr = new T[len]; 
        
        // Копируем элементы из входящего массива в наш внутренний через арифметику указателей
        for(int i = 0; i < len; i++)
            *(arr + i) = *(a + i);
    }

    // Метод для вывода содержимого массива на экран
    void get() {
        for(int i = 0; i < len; i++)
            cout << *(arr + i) << " "; // Обращение к элементам через указатели

        cout << endl;
    }

    // Деструктор: автоматически вызывается при уничтожении объекта.
    // Освобождает выделенную динамическую память, предотвращая утечку (memory leak).
    ~Arrays() {
        delete[] arr;
    }
};


int main() {
    
    // 1. Создание объекта класса для работы с целыми числами (int)
    int arr1[] = { 3, 2, 6 };
    Arrays<int> obj1(arr1, 3); // Явное указание шаблона <int>
    obj1.get();

    // 2. Создание объекта для чисел с плавающей точкой (float)
    float arr2[] = { 3.1, 2.0, 6.3 };
    Arrays obj2(arr2, 3);      // Компилятор сам догадывается о типе <float> на основе передаваемого массива
    obj2.get();

    return 0;
}